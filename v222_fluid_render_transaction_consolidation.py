# Current order before this patch:
#   V18.0 route wrapper
#     -> V17.8 consolidated visual wrapper
#       -> V15.8 fluid/render-settle wrapper
#         -> older render chain
#
# V17.8 already directly wraps V15.8. Convert V15.8's wrapper into an exported
# transaction helper and call it from V17.8 at the exact same point.
#
# This preserves:
# - V17.8 re-entrant guard order
# - V15.8 pre-render __fjzRenderSettleV158=true
# - cache-first loader behavior during render
# - V15.8 release RAF scheduling BEFORE V17.8 final-pass scheduling
# - V18.0 route/scroll outer authority
